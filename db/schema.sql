CREATE TABLE IF NOT EXISTS accounts (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email text NOT NULL UNIQUE CHECK (email = lower(email)),
  name text NOT NULL,
  password_hash text NOT NULL,
  role text NOT NULL CHECK (role IN ('Cliente','Empleado','Superadmin')),
  phone text NOT NULL DEFAULT '',
  address text NOT NULL DEFAULT '',
  active boolean NOT NULL DEFAULT true
);
CREATE TABLE IF NOT EXISTS sessions (
  token_hash text PRIMARY KEY,
  user_id integer NOT NULL REFERENCES accounts,
  expires_at timestamptz NOT NULL
);
CREATE TABLE IF NOT EXISTS categories (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL UNIQUE,
  active boolean NOT NULL DEFAULT true
);
CREATE TABLE IF NOT EXISTS products (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL,
  description text NOT NULL,
  image text NOT NULL,
  category_id integer NOT NULL REFERENCES categories,
  price numeric(12,2) NOT NULL CHECK(price >= 0),
  stock integer NOT NULL CHECK(stock >= 0),
  min_stock integer NOT NULL CHECK(min_stock >= 0),
  active boolean NOT NULL DEFAULT true
);
CREATE TABLE IF NOT EXISTS orders (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id integer NOT NULL REFERENCES accounts,
  address text NOT NULL,
  shipping numeric(12,2) NOT NULL,
  total numeric(18,2) NOT NULL,
  status text NOT NULL CHECK(status IN ('Pendiente','Confirmado','En preparación','En camino','Entregado','Cancelado')),
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS order_items (
  order_id integer NOT NULL REFERENCES orders,
  product_id integer NOT NULL REFERENCES products,
  name text NOT NULL,
  price numeric(12,2) NOT NULL,
  quantity integer NOT NULL CHECK(quantity > 0),
  PRIMARY KEY(order_id,product_id)
);
CREATE TABLE IF NOT EXISTS order_history (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id integer NOT NULL REFERENCES orders,
  status text NOT NULL,
  actor text NOT NULL,
  actor_id integer NOT NULL REFERENCES accounts,
  reason text NOT NULL DEFAULT '',
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS orders_customer ON orders(user_id,id);
CREATE INDEX IF NOT EXISTS history_order ON order_history(order_id,id);
